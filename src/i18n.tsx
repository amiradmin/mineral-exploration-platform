export function LanguageProvider({children}:{children:React.ReactNode}){
  const [language,setLanguageState]=useState<Language>(()=>{
    try{return window.localStorage.getItem('data-mine-language')==='fa'?'fa':'en'}catch{return 'en'}
  })
  const setLanguage=(lang:Language)=>setLanguageState(lang)
  useEffect(()=>{
    document.documentElement.lang=language
    document.documentElement.dir=language==='fa'?'rtl':'ltr'
    try{window.localStorage.setItem('data-mine-language',language)}catch{}
  },[language])
  return <Context.Provider value={{language,setLanguage,t:s=>language==='fa'?(dictionary[s]??s):s,locale:language==='fa'?'fa-IR':'en-US'}}>{children}</Context.Provider>
}
